// 위기 낱말 안전망. AI 답과 상관없이 브라우저와 서버가 둘 다 확인한다(계획서 6단계).
// 띄어쓰기와 맞춤법이 흐린 입력도 잡도록 공백을 지운 뒤 찾는다. 활용형("죽을 거예요", "그었어요")까지 잡는다.
// "힘들어 죽겠다"처럼 흔한 과장 표현은 넣지 않았다.

const PATTERNS: RegExp[] = [
  /자살/,
  /자해/,
  /죽고싶/,
  /죽을(거|꺼|래|까|게|려고|생각)/,
  /죽어(버리|버릴|버렸)/,
  /죽는게(나|낫)/,
  /죽으려/,
  /살기(싫|가싫)/,
  /살고싶지(않|않아)/,
  /사라지고싶/,
  /사라져(버리|버릴)/,
  /없어지고싶/,
  /다그만두고싶/,
  /다끝내고싶/,
  /목숨/,
  /유서/,
  /투신/,
  /뛰어내리/,
  /목을?매/,
  /(손목|팔)을?(긋|그었|그을|그어)/,
  /약을?(다)?(모아|모았|먹어버리|한꺼번에)/,
  /세상을?(떠나고싶|뜨고싶)/,
];

export function hasCrisisWords(text: string): boolean {
  const flat = text.replace(/\s+/g, "");
  return PATTERNS.some((p) => p.test(flat));
}
